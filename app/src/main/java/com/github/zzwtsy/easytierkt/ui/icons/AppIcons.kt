/**
 * 从 fonts.google.com/icons 导出的 Material Symbols Rounded 图标（24px，已平移到 960 视口）。
 * 官方已停止更新 material-icons 库并推荐 Material Symbols；仅保留用到的图标，不引入图标库依赖。
 */
private fun materialSymbol(
    name: String,
    pathData: String,
): ImageVector =
    ImageVector
        .Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 960f,
            viewportHeight = 960f,
        ).addPath(
            pathData = PathParser().parsePathString(pathData).toNodes(),
            fill = SolidColor(Color.Black),
        ).build()

